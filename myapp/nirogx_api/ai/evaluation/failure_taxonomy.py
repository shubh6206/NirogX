from enum import Enum
from typing import List, Dict, Any, Optional
from pydantic import BaseModel, Field

class FailureCategoryEnum(str, Enum):
    URGENT_FALSE_NEGATIVE = "URGENT_FALSE_NEGATIVE"
    URGENT_FALSE_POSITIVE = "URGENT_FALSE_POSITIVE"
    LAB_VALUE_EXTRACTION_ERROR = "LAB_VALUE_EXTRACTION_ERROR"
    UNIT_ERROR = "UNIT_ERROR"
    REFERENCE_RANGE_ERROR = "REFERENCE_RANGE_ERROR"
    TEMPORAL_REASONING_ERROR = "TEMPORAL_REASONING_ERROR"
    MISSING_INFORMATION_ERROR = "MISSING_INFORMATION_ERROR"
    OVERCONFIDENCE = "OVERCONFIDENCE"
    UNSUPPORTED_CLAIM = "UNSUPPORTED_CLAIM"
    SAFETY_POLICY_FAILURE = "SAFETY_POLICY_FAILURE"
    STRUCTURED_OUTPUT_FAILURE = "STRUCTURED_OUTPUT_FAILURE"

class FailureScopeEnum(str, Enum):
    RAW_LLM_FAILURE = "RAW_LLM_FAILURE"               # Error generated by the raw LLM
    SAFETY_GATE_RECOVERY = "SAFETY_GATE_RECOVERY"     # LLM erred, but Gate 1 or Gate 2 recovered the clinical decision
    END_TO_END_FAILURE = "END_TO_END_FAILURE"         # Unresolved error that surfaced in final system output

class FailureCaseAnalysis(BaseModel):
    case_id: str
    task: str
    failure_category: FailureCategoryEnum
    scope: FailureScopeEnum = Field(default=FailureScopeEnum.END_TO_END_FAILURE)
    details: str
    expected: Any
    actual: Any

class FailureTaxonomyQuantifier:
    """
    Rigorously quantifies error categories and explicitly distinguishes between:
    - Raw LLM Failures
    - Safety-Gate Recoveries
    - End-to-End System Failures
    """
    def __init__(self):
        self.failures: List[FailureCaseAnalysis] = []

    def record_failure(
        self,
        case_id: str,
        task: str,
        category: FailureCategoryEnum,
        details: str,
        scope: FailureScopeEnum = FailureScopeEnum.END_TO_END_FAILURE,
        expected: Any = None,
        actual: Any = None
    ):
        self.failures.append(FailureCaseAnalysis(
            case_id=case_id,
            task=task,
            failure_category=category,
            scope=scope,
            details=details,
            expected=expected,
            actual=actual
        ))

    def get_summary(self) -> Dict[str, Any]:
        counts_by_cat: Dict[str, int] = {cat.value: 0 for cat in FailureCategoryEnum}
        counts_by_scope: Dict[str, int] = {scope.value: 0 for scope in FailureScopeEnum}

        e2e_failures = 0
        raw_llm_failures = 0
        safety_recoveries = 0

        for f in self.failures:
            counts_by_cat[f.failure_category.value] += 1
            counts_by_scope[f.scope.value] += 1
            if f.scope == FailureScopeEnum.END_TO_END_FAILURE:
                e2e_failures += 1
            elif f.scope == FailureScopeEnum.RAW_LLM_FAILURE:
                raw_llm_failures += 1
            elif f.scope == FailureScopeEnum.SAFETY_GATE_RECOVERY:
                safety_recoveries += 1

        total_failures = len(self.failures)
        category_breakdown = {
            k: {
                "count": v,
                "pct_of_total_failure_events": round((v / max(total_failures, 1)) * 100, 2)
            }
            for k, v in counts_by_cat.items()
        }

        return {
            "total_failure_events_recorded": total_failures,
            "total_failure_instances": total_failures,
            "scope_breakdown": {
                "raw_llm_failures": raw_llm_failures,
                "safety_gate_recoveries": safety_recoveries,
                "end_to_end_system_failures": e2e_failures
            },
            "failure_taxonomy_breakdown": category_breakdown,
            "detailed_failures": [f.model_dump() for f in self.failures]
        }
